#!/usr/bin/env python3
"""Requirements traceability: which tests verify which requirement.

    scripts/trace.py            write docs/trace-matrix.md
    scripts/trace.py --check    fail if the committed matrix is out of date

Reads the ids from docs/requirements.md and the tags from the tests:
    tests/*.cpp           REQ_nnn tokens in TEST / TEST_F / TEST_P names
    tests/CMakeLists.txt  REQ_nnn tokens in add_test(NAME ...) names
    tests/sil/*.py        @pytest.mark.req("REQ-nnn") above a test function

Exit status 1, with the reason printed, when any requirement has no test, when
a test names an id that does not exist, or (with --check) when the committed
matrix differs from what the sources say. Tests without an id are allowed and
counted; they are tests of implementation detail, not of a requirement.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUIREMENTS = ROOT / "docs" / "requirements.md"
MATRIX = ROOT / "docs" / "trace-matrix.md"
TESTS = ROOT / "tests"

REQ_ROW = re.compile(r"^\|\s*(REQ-\d{3})\s*\|\s*(\w+)\s*\|\s*(.+?)\s*\|\s*$")
GTEST = re.compile(r"^\s*TEST(?:_F|_P)?\(\s*(\w+)\s*,\s*(\w+)\s*\)")
CTEST = re.compile(r"add_test\(\s*NAME\s+(\w+)")
PYTEST_MARK = re.compile(r"^\s*@pytest\.mark\.req\(\s*[\"'](REQ-\d{3})[\"']\s*\)")
PYTEST_DEF = re.compile(r"^\s*def\s+(test_\w+)\s*\(")
ID_IN_NAME = re.compile(r"REQ_(\d{3})")


def read_requirements() -> dict[str, tuple[str, str]]:
    """{'REQ-001': (type, text)}, in file order."""
    found = {}
    for line in REQUIREMENTS.read_text().splitlines():
        match = REQ_ROW.match(line)
        if match:
            req_id, kind, text = match.groups()
            if req_id in found:
                sys.exit(f"{REQUIREMENTS.name}: {req_id} listed twice")
            found[req_id] = (kind, text)
    if not found:
        sys.exit(f"{REQUIREMENTS.name}: no requirement rows found")
    return found


def ids_in_name(name: str) -> list[str]:
    return [f"REQ-{digits}" for digits in ID_IN_NAME.findall(name)]


def read_tests() -> list[tuple[str, str, list[str]]]:
    """[(level, test name, [ids])] for every test the sources declare."""
    tests = []
    for path in sorted(TESTS.glob("*.cpp")):
        for line in path.read_text().splitlines():
            match = GTEST.match(line)
            if match:
                suite, name = match.groups()
                tests.append(("unit", f"{suite}.{name}", ids_in_name(name)))
    for match in CTEST.finditer((TESTS / "CMakeLists.txt").read_text()):
        tests.append(("unit", match.group(1), ids_in_name(match.group(1))))
    for path in sorted((TESTS / "sil").glob("test_*.py")):
        pending: list[str] = []
        for line in path.read_text().splitlines():
            mark = PYTEST_MARK.match(line)
            if mark:
                pending.append(mark.group(1))
                continue
            definition = PYTEST_DEF.match(line)
            if definition:
                tests.append(("SIL", f"{path.stem}::{definition.group(1)}", pending))
                pending = []
            elif line.strip() and not line.lstrip().startswith("@"):
                pending = []  # a mark that is not followed by a def does not count
    return tests


def build_matrix(requirements, tests) -> tuple[str, list[str]]:
    """The markdown text and the list of problems (empty when all is well)."""
    by_req: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    problems = []
    for level, name, ids in tests:
        for req_id in ids:
            if req_id not in requirements:
                problems.append(f"{name} names {req_id}, which is not in {REQUIREMENTS.name}")
            by_req[req_id][level].append(name)

    rows = []
    tested = 0
    for req_id, (kind, text) in requirements.items():
        unit = by_req[req_id]["unit"]
        sil = by_req[req_id]["SIL"]
        if unit or sil:
            tested += 1
            status = "tested"
        else:
            status = "**UNTESTED**"
            problems.append(f"{req_id} has no test")
        rows.append(f"| {req_id} | {kind} | {text} | {'<br>'.join(unit) or '-'} | "
                    f"{'<br>'.join(sil) or '-'} | {status} |")

    tagged = sum(1 for _, _, ids in tests if ids)
    summary = (f"{tested} of {len(requirements)} requirements tested; "
               f"{tagged} of {len(tests)} test declarations carry an id")
    text = "\n".join([
        "# Trace matrix",
        "",
        "Generated by `scripts/trace.py` from `docs/requirements.md` and the test",
        "sources; do not edit. CI regenerates it and fails if this file is stale.",
        "A parameterized GoogleTest counts once here and many times in ctest.",
        "",
        f"**{summary}.**",
        "",
        "| Id | Type | Requirement | Unit tests | SIL tests | Status |",
        "|----|------|-------------|------------|-----------|--------|",
        *rows,
        "",
    ])
    return text, problems, summary


def main(argv: list[str]) -> int:
    check = argv[1:] == ["--check"]
    if argv[1:] and not check:
        sys.exit("usage: scripts/trace.py [--check]")

    text, problems, summary = build_matrix(read_requirements(), read_tests())
    print(summary)
    for problem in problems:
        print(f"trace: {problem}", file=sys.stderr)

    if check:
        if not MATRIX.exists() or MATRIX.read_text() != text:
            print(f"trace: {MATRIX.relative_to(ROOT)} is out of date; "
                  "run scripts/trace.py and commit it", file=sys.stderr)
            return 1
    else:
        MATRIX.write_text(text)
        print(f"wrote {MATRIX.relative_to(ROOT)}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
